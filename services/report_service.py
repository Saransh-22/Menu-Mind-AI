def _render_executive_summary(state: AgentState) -> str:
    parts = []
    if state.sales_summary:
        s = state.sales_summary
        parts.append(
            f"<p>Total revenue: <strong>₹{s.total_revenue:,.2f}</strong> | "
            f"Units sold: <strong>{s.total_units:,}</strong> | "
            f"Period: {s.period_start} – {s.period_end}</p>"
        )
    if state.recommendations:
        from collections import Counter
        counts = Counter(r.action.value for r in state.recommendations)
        items = " | ".join(f"{v} {k}" for k, v in counts.items())
        parts.append(f"<p>Recommendations: {items}</p>")
    if not parts:
        parts.append("<p>Analysis did not produce sufficient data for a summary.</p>")
    return "\n".join(parts)


def _render_quality_html(quality_reports: list) -> str:
    if not quality_reports:
        return "<p>No quality reports available.</p>"
    rows = ""
    for r in quality_reports:
        rows += (
            f"<tr><td>{r.file_type}</td><td>{r.total_records}</td>"
            f"<td>{r.accepted_records}</td><td>{r.duplicate_records}</td>"
            f"<td>{r.quality_score:.0%}</td></tr>"
        )
    return f"""
<table>
<thead><tr><th>File</th><th>Total</th><th>Accepted</th><th>Duplicates</th><th>Score</th></tr></thead>
<tbody>{rows}</tbody>
</table>"""


def _render_sales_html(state: AgentState) -> str:
    if not state.sales_summary:
        return "<p>No sales analysis available.</p>"
    s = state.sales_summary
    rows = ""
    for item in s.top_items:
        rows += (
            f"<tr><td>{item.item_name}</td><td>{item.category or '—'}</td>"
            f"<td>₹{item.total_revenue:,.2f}</td><td>{item.total_quantity:,}</td>"
            f"<td>{item.revenue_contribution_pct or 0:.1f}%</td>"
            f"<td>{item.period_trend or '—'}</td></tr>"
        )
    return f"""
<table>
<thead><tr><th>Item</th><th>Category</th><th>Revenue</th><th>Units</th><th>Share</th><th>Trend</th></tr></thead>
<tbody>{rows}</tbody>
</table>"""


def _render_recommendations_html(recs: list[Recommendation]) -> str:
    if not recs:
        return "<p>No recommendations generated.</p>"
    html = ""
    for rec in recs:
        html += f"""
<div class="card">
  <h3>{rec.item_name} &nbsp;<span class="badge {rec.action.value}">{rec.action.value}</span>
    &nbsp;<span class="{rec.priority.value}">[{rec.priority.value.upper()} priority]</span></h3>
  <p><strong>Confidence:</strong> {rec.confidence_score:.0%} ({rec.confidence_label()})</p>
  <p><strong>Reasoning:</strong> {rec.reasoning}</p>
  <p><strong>Expected benefits:</strong> {rec.expected_benefits}</p>
  <p><strong>Potential risks:</strong> {rec.potential_risks}</p>
  <p><strong>Missing information:</strong> {rec.missing_information}</p>
  <p><strong>Next steps:</strong> {"; ".join(rec.next_steps)}</p>
  <p><strong>Success metrics:</strong> {rec.success_metrics}</p>
</div>"""
    return html


# ─── CSV export ───────────────────────────────────────────────────────────────

def recommendations_to_csv(recs: list[Recommendation]) -> bytes:
    rows = []
    for r in recs:
        rows.append({
            "item_id": r.item_id or "",
            "item_name": r.item_name,
            "action": r.action.value,
            "priority": r.priority.value,
            "confidence_score": r.confidence_score,
            "reasoning": r.reasoning,
            "expected_benefits": r.expected_benefits,
            "potential_risks": r.potential_risks,
            "missing_information": r.missing_information,
            "next_steps": "; ".join(r.next_steps),
            "success_metrics": r.success_metrics,
        })
    df = pd.DataFrame(rows)
    buf = io.BytesIO()
    df.to_csv(buf, index=False)
    return buf.getvalue()
